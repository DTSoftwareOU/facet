/** Builds the deterministic test vectors shared with the Android client (docs/test-vectors.json). */
import {
  AAD,
  COMPRESS_THRESHOLD,
  encodeRecoveryCode,
  INFO,
  normalizePassword,
  passwordKeys,
  recoveryKeys,
  sealBlob,
  sealRecord,
  wrapVaultKey,
} from './client-crypto.js';

const hex = (b: Buffer) => b.toString('hex');
const b64 = (b: Buffer) => b.toString('base64');
const range = (start: number, length: number) => Buffer.from(Array.from({ length }, (_, i) => (start + i) & 0xff));

export const INPUTS = {
  password: 'correct horse battery staple ✓',
  saltHex: hex(range(0x00, 16)),
  iterations: 100_000,
  vaultKeyHex: hex(range(0x20, 32)),
  recoveryCodeBytesHex: hex(range(0xc0, 20)),
  nonces: {
    passwordWrapHex: hex(range(0x10, 12)),
    recoveryWrapHex: hex(range(0x60, 12)),
    recordSmallHex: hex(range(0x30, 12)),
    recordCompressedHex: hex(range(0x40, 12)),
    blobHex: hex(range(0x50, 12)),
  },
};

export const SMALL_RECORD = {
  type: 'conv',
  id: 'conv_test_1',
  json: JSON.stringify({ title: 'Hello, Facet', pinned: false, createdAt: 1767225600000 }),
};

function longJson(): string {
  const paragraphs = Array.from(
    { length: 12 },
    (_, i) =>
      `Paragraph ${i + 1}: Facet keeps every conversation end-to-end encrypted, so the sync server only ever sees ciphertext. ` +
      `Unicode check: café, naïve, 日本語, emoji 💎.`,
  );
  return JSON.stringify({ role: 'assistant', conversationId: 'conv_test_1', text: paragraphs.join('\n\n') });
}

export const COMPRESSED_RECORD = { type: 'msg', id: 'msg_test_1', json: longJson() };

export const BLOB = { id: 'blob_test_1', plaintext: Buffer.from('%PDF-1.7 tiny fake attachment\n', 'utf8') };

export function buildVectors() {
  const salt = Buffer.from(INPUTS.saltHex, 'hex');
  const vaultKey = Buffer.from(INPUTS.vaultKeyHex, 'hex');
  const code = Buffer.from(INPUTS.recoveryCodeBytesHex, 'hex');
  const n = (k: keyof typeof INPUTS.nonces) => Buffer.from(INPUTS.nonces[k], 'hex');

  const keys = passwordKeys(INPUTS.password, salt, INPUTS.iterations);
  const rk = recoveryKeys(code);
  const wrapped = wrapVaultKey(keys.wrapKey, vaultKey, AAD.vaultKey, n('passwordWrapHex'));
  const recoveryWrapped = wrapVaultKey(rk.wrapKey, vaultKey, AAD.vaultKeyRecovery, n('recoveryWrapHex'));
  const small = sealRecord(vaultKey, SMALL_RECORD.type, SMALL_RECORD.id, SMALL_RECORD.json, n('recordSmallHex'));
  const compressed = sealRecord(vaultKey, COMPRESSED_RECORD.type, COMPRESSED_RECORD.id, COMPRESSED_RECORD.json, n('recordCompressedHex'));
  const blob = sealBlob(vaultKey, BLOB.id, BLOB.plaintext, n('blobHex'));

  const nfkcInput = 'Ｆａｃｅｔ ﬁ café';

  return {
    version: 1,
    notes: [
      'Generated by server/scripts/gen-test-vectors.ts from the reference client in server/test/client-crypto.ts. Spec: docs/SECURITY.md.',
      'Binary values are lowercase hex (*Hex) or standard padded base64 (*B64). Strings are UTF-8.',
      'HKDF-SHA256 uses a salt of 32 zero bytes and 32-byte output; info strings are ASCII.',
      'Record envelopes: 0x01 || flags || nonce(12) || AES-256-GCM(ciphertext||tag). flags bit0 = raw DEFLATE (no zlib header), used when the UTF-8 JSON is longer than 1024 bytes.',
      'The small record and the blob are deterministic: an implementation must reproduce envelopeB64 byte-for-byte.',
      'The compressed record is NOT required to match byte-for-byte (DEFLATE output may differ between zlib builds/levels): decrypting envelopeB64 and inflating must reproduce plaintextJson exactly; and your own seal must round-trip through your own open.',
      'The vault key wraps are deterministic given the fixed nonces and must match exactly.',
    ],
    constants: {
      info: INFO,
      aad: {
        vaultKey: AAD.vaultKey,
        vaultKeyRecovery: AAD.vaultKeyRecovery,
        recordFormat: 'facet:rec:v1:<type>:<id>',
        blobFormat: 'facet:blob:v1:<blobId>',
      },
      compressThresholdBytes: COMPRESS_THRESHOLD,
      crockfordAlphabet: '0123456789ABCDEFGHJKMNPQRSTVWXYZ',
    },
    nfkc: {
      input: nfkcInput,
      normalized: nfkcInput.normalize('NFKC'),
      normalizedUtf8Hex: hex(normalizePassword(nfkcInput)),
    },
    inputs: INPUTS,
    password: {
      normalizedUtf8Hex: hex(normalizePassword(INPUTS.password)),
      masterKeyHex: hex(keys.masterKey),
      authKeyHex: hex(keys.authKey),
      authHashB64: b64(keys.authKey),
      wrapKeyHex: hex(keys.wrapKey),
      wrappedVaultKeyHex: hex(wrapped),
      wrappedVaultKeyB64: b64(wrapped),
    },
    recovery: {
      codeText: encodeRecoveryCode(code),
      codeTextVariantsThatMustParse: [
        encodeRecoveryCode(code).toLowerCase(),
        encodeRecoveryCode(code).replace(/-/g, ' '),
        encodeRecoveryCode(code).replace(/-/g, ''),
      ],
      recoveryAuthKeyHex: hex(rk.authKey),
      recoveryAuthHashB64: b64(rk.authKey),
      recoveryWrapKeyHex: hex(rk.wrapKey),
      recoveryWrappedVaultKeyHex: hex(recoveryWrapped),
      recoveryWrappedVaultKeyB64: b64(recoveryWrapped),
    },
    records: [
      {
        type: SMALL_RECORD.type,
        id: SMALL_RECORD.id,
        aad: AAD.record(SMALL_RECORD.type, SMALL_RECORD.id),
        plaintextJson: SMALL_RECORD.json,
        compressed: false,
        nonceHex: INPUTS.nonces.recordSmallHex,
        envelopeB64: b64(small),
        deterministic: true,
      },
      {
        type: COMPRESSED_RECORD.type,
        id: COMPRESSED_RECORD.id,
        aad: AAD.record(COMPRESSED_RECORD.type, COMPRESSED_RECORD.id),
        plaintextJson: COMPRESSED_RECORD.json,
        plaintextUtf8Bytes: Buffer.byteLength(COMPRESSED_RECORD.json, 'utf8'),
        compressed: true,
        nonceHex: INPUTS.nonces.recordCompressedHex,
        envelopeB64: b64(compressed),
        deterministic: false,
      },
    ],
    blob: {
      id: BLOB.id,
      aad: AAD.blob(BLOB.id),
      plaintextHex: hex(BLOB.plaintext),
      nonceHex: INPUTS.nonces.blobHex,
      envelopeB64: b64(blob),
    },
  };
}
